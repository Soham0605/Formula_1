import os
SHOTS = os.environ.get("SHOTS", "/tmp/shots")
def run(pg):
    pg.wait_for_selector("#picker-list .race-opt", state="attached", timeout=30000)
    pg.click("#picker-btn"); pg.click("#picker-list .race-opt:not([disabled])")
    pg.wait_for_selector("#sec-driver:not(.hidden)", timeout=60000); pg.wait_for_timeout(1500)
    pg.locator("#sec-driver").screenshot(path=f"{SHOTS}/v2_drivers.png")
    pg.click("#drivers .drv[data-id=max_verstappen]")
    pg.wait_for_selector("#sec-strat:not(.hidden)", timeout=120000)
    pg.wait_for_function("!document.querySelector('#loader').classList.contains('on')", timeout=120000)
    pg.mouse.click(5, 5)
    for _ in range(10): pg.keyboard.press("ArrowRight")
    pg.keyboard.press("ArrowDown")
    pg.keyboard.press("Enter")
    pg.wait_for_selector("#callsheet:not(.hidden)", timeout=120000)
    pg.wait_for_function("!document.querySelector('#loader').classList.contains('on')", timeout=120000)
    pg.wait_for_timeout(1200)
    pg.locator("#console").screenshot(path=f"{SHOTS}/v2_console.png")
    pg.locator("#callsheet").screenshot(path=f"{SHOTS}/v2_callsheet.png")
    pg.click("#callsheet .cs-stint >> nth=-1"); pg.wait_for_timeout(800)
    pg.locator("#callsheet").screenshot(path=f"{SHOTS}/v2_callsheet_last.png")
    pg.click("#sync-pull"); pg.wait_for_timeout(3000)
    print("sync msg:", pg.inner_text("#sync-msg"))
