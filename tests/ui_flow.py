"""Drive the dashboard: race -> cards -> driver -> prediction -> what-if. Used by tests/run_browser.py --script."""
import os, time
SHOTS = os.environ.get("SHOTS", "/tmp/shots")

def run(pg):
    t0 = time.time()
    pg.wait_for_selector("#picker-list .race-opt", state="attached", timeout=30000)
    pg.wait_for_timeout(1800)
    pg.screenshot(path=f"{SHOTS}/01_hero.png")
    pg.click("#picker-btn"); pg.wait_for_timeout(500)
    pg.screenshot(path=f"{SHOTS}/02_picker.png")
    n_enabled = pg.eval_on_selector_all("#picker-list .race-opt:not([disabled])", "els => els.length")
    print("enabled races:", n_enabled)
    pg.click("#picker-list .race-opt:not([disabled])")
    pg.wait_for_selector("#sec-driver:not(.hidden)", timeout=60000)
    pg.wait_for_timeout(2500)
    pg.locator("#sec-event").screenshot(path=f"{SHOTS}/03_cards.png")
    pg.click("#cards4 .card >> nth=0"); pg.wait_for_timeout(900)
    pg.screenshot(path=f"{SHOTS}/04_weather_modal.png")
    pg.keyboard.press("Escape"); pg.wait_for_timeout(400)
    pg.click("#cards4 .card >> nth=1"); pg.wait_for_timeout(1200)
    pg.screenshot(path=f"{SHOTS}/05_track_modal.png")
    pg.keyboard.press("Escape"); pg.wait_for_timeout(400)
    pg.locator("#sec-driver").screenshot(path=f"{SHOTS}/06_drivers.png")
    pg.click("#drivers .drv[data-id=max_verstappen]")
    pg.wait_for_timeout(1200)
    pg.screenshot(path=f"{SHOTS}/07_loader.png")
    pg.wait_for_selector("#sec-strat:not(.hidden)", timeout=120000)
    pg.wait_for_function("!document.querySelector('#loader').classList.contains('on')", timeout=120000)
    pg.wait_for_timeout(1500)
    print("pre-race done at", round(time.time() - t0, 1), "s")
    pg.locator("#sec-pred").screenshot(path=f"{SHOTS}/08_pred.png")
    pg.locator("#sec-strat").screenshot(path=f"{SHOTS}/09_strat.png")
    pg.locator("#console").scroll_into_view_if_needed(); pg.wait_for_timeout(600)
    pg.mouse.click(5, 5)
    for _ in range(3): pg.keyboard.press("ArrowRight")
    for _ in range(2): pg.keyboard.press("ArrowDown")
    print("summary:", pg.inner_text("#sum"))
    pg.locator("#sec-live").screenshot(path=f"{SHOTS}/10_console.png")
    pg.keyboard.press("Enter")
    pg.wait_for_selector("#history .wi", timeout=120000)
    pg.wait_for_function("!document.querySelector('#loader').classList.contains('on')", timeout=120000)
    pg.wait_for_timeout(1500)
    print("what-if 1:", pg.inner_text("#history .wi .wi-head")[:200].replace("\n", " | "))
    # SC on lap 18, P3, mediums 18 laps
    for _ in range(15): pg.keyboard.press("ArrowRight")
    pg.keyboard.press("ArrowUp"); pg.keyboard.press("s")
    print("summary2:", pg.inner_text("#sum"))
    pg.keyboard.press("Enter")
    pg.wait_for_function("document.querySelectorAll('#history .wi').length >= 2", timeout=120000)
    pg.wait_for_function("!document.querySelector('#loader').classList.contains('on')", timeout=120000)
    pg.wait_for_timeout(1500)
    print("what-if 2:", pg.inner_text("#history .wi .wi-head")[:220].replace("\n", " | "))
    pg.locator("#history .wi >> nth=0").screenshot(path=f"{SHOTS}/11_whatif.png")
    pg.screenshot(path=f"{SHOTS}/12_full.png", full_page=True)
    print("total", round(time.time() - t0, 1), "s")
